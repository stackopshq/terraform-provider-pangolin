func (r *RedirectResource) ConfigValidators(_ context.Context) []resource.ConfigValidator {
	return []resource.ConfigValidator{
		resourcevalidator.ExactlyOneOf(
			path.MatchRoot("resource_id"),
			path.MatchRoot("domain_id"),
		),
	}
}

// ValidateConfig rejects combinations the server ignores or refuses.
func (r *RedirectResource) ValidateConfig(ctx context.Context, req resource.ValidateConfigRequest, resp *resource.ValidateConfigResponse) {
	var rewritePath, rewriteType types.String
	var resourceID types.Int64
	var subdomain types.String
	var ssl types.Bool
	resp.Diagnostics.Append(req.Config.GetAttribute(ctx, path.Root("rewrite_path"), &rewritePath)...)
	resp.Diagnostics.Append(req.Config.GetAttribute(ctx, path.Root("rewrite_path_type"), &rewriteType)...)
	resp.Diagnostics.Append(req.Config.GetAttribute(ctx, path.Root("resource_id"), &resourceID)...)
	resp.Diagnostics.Append(req.Config.GetAttribute(ctx, path.Root("ssl"), &ssl)...)
	resp.Diagnostics.Append(req.Config.GetAttribute(ctx, path.Root("subdomain"), &subdomain)...)
	if resp.Diagnostics.HasError() {
		return
	}

	if !rewriteType.IsNull() && !rewriteType.IsUnknown() && rewriteType.ValueString() != "stripPrefix" &&
		rewritePath.IsNull() {
		resp.Diagnostics.AddAttributeError(path.Root("rewrite_path"),
			"rewrite_path is required",
			fmt.Sprintf("rewrite_path is required unless rewrite_path_type is %q (got %q).",
				"stripPrefix", rewriteType.ValueString()))
	}

	// Unknown values may still resolve to null.
	hasResource := !resourceID.IsNull() && !resourceID.IsUnknown()
	if hasResource && !subdomain.IsNull() && !subdomain.IsUnknown() {
		resp.Diagnostics.AddAttributeError(path.Root("subdomain"),
			"subdomain cannot be combined with resource_id",
			"A redirect attached to a resource listens on the resource's own domain; the server stores subdomain but ignores it. Remove subdomain or attach the redirect to a domain with domain_id.")
	}

	if hasResource && !ssl.IsNull() && !ssl.IsUnknown() && !ssl.ValueBool() {
		resp.Diagnostics.AddAttributeError(path.Root("ssl"),
			"ssl cannot be disabled for a resource-attached redirect",
			"The server forces ssl to true for a redirect attached to a resource. Remove ssl or attach the redirect to a domain.")
	}
}

func (r *RedirectResource) Configure(_ context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	if req.ProviderData == nil {
		return
	}
	c, ok := req.ProviderData.(*client.Client)
	if !ok {
		resp.Diagnostics.AddError("Unexpected Resource Configure Type", "Expected *client.Client")
		return
	}
	r.client = c
}

func (r *RedirectResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan RedirectModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	createReq := &client.CreateRedirectRequest{
		Name:            plan.Name.ValueString(),
		DestinationHost: plan.DestinationHost.ValueString(),
		DomainID:        tfconv.PtrFromKnownString(plan.DomainID),
		Subdomain:       tfconv.PtrFromKnownString(plan.Subdomain),
		PathMatchType:   tfconv.PtrFromKnownString(plan.PathMatchType),
		MatchPath:       tfconv.PtrFromKnownString(plan.MatchPath),
		RewritePath:     tfconv.PtrFromKnownString(plan.RewritePath),
		RewritePathType: tfconv.PtrFromKnownString(plan.RewritePathType),
	}
	createReq.ResourceID = tfconv.PtrFromKnownInt64AsInt(plan.ResourceID)
	createReq.Priority = tfconv.PtrFromKnownInt64AsInt(plan.Priority)
	createReq.Permanent = tfconv.PtrFromKnownBool(plan.Permanent)
	createReq.SSL = tfconv.PtrFromKnownBool(plan.SSL)
	createReq.Enabled = tfconv.PtrFromKnownBool(plan.Enabled)

	// Create does not accept niceId: set it with an update, which re-reads.
	wantNiceID := plan.NiceID
	applyNiceID := !wantNiceID.IsNull() && !wantNiceID.IsUnknown()
	var created *client.Redirect
	var err error
	if applyNiceID {
		created, err = r.client.CreateRedirectBare(ctx, createReq)
	} else {
		created, err = r.client.CreateRedirect(ctx, createReq)
	}
	if err != nil {
		resp.Diagnostics.AddError("Failed to create redirect", err.Error())
		return
	}

	// The update is built from the config, not the bare create response.
	planned := plan
	hydrateRedirectState(&plan, created)
	if applyNiceID {
		// Save first: a failed update leaves a tainted resource, not an orphan.
		resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
		updated, err := r.client.UpdateRedirect(ctx, created.RedirectID, buildRedirectUpdateRequest(&planned, created.NiceID))
		if err != nil {
			resp.Diagnostics.AddError("Failed to set redirect nice_id after creation", err.Error())
			return
		}
		hydrateRedirectState(&plan, updated)
	}

	keepEquivalentValues(&planned, &plan)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *RedirectResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state RedirectModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	id, err := strconv.Atoi(state.ID.ValueString())
	if err != nil {
		resp.Diagnostics.AddError("Invalid ID", fmt.Sprintf("Cannot parse redirect ID %q as integer", state.ID.ValueString()))
		return
	}

	redirect, err := r.client.GetRedirect(ctx, id)
	if err != nil {
		if errors.Is(err, client.ErrNotFound) {
			resp.State.RemoveResource(ctx)
			return
		}
		resp.Diagnostics.AddError("Failed to read redirect", err.Error())
		return
	}

	prior := state
	hydrateRedirectState(&state, redirect)
	keepEquivalentValues(&prior, &state)
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

func (r *RedirectResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan, state RedirectModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	id, err := strconv.Atoi(state.ID.ValueString())
	if err != nil {
		resp.Diagnostics.AddError("Invalid ID", fmt.Sprintf("Cannot parse redirect ID %q as integer", state.ID.ValueString()))
		return
	}

	updated, err := r.client.UpdateRedirect(ctx, id, buildRedirectUpdateRequest(&plan, state.NiceID.ValueString()))
	if err != nil {
		resp.Diagnostics.AddError("Failed to update redirect", err.Error())
		return
	}

	planned := plan
	hydrateRedirectState(&plan, updated)
	keepEquivalentValues(&planned, &plan)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *RedirectResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state RedirectModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	id, err := strconv.Atoi(state.ID.ValueString())
	if err != nil {
		resp.Diagnostics.AddError("Invalid ID", fmt.Sprintf("Cannot parse redirect ID %q as integer", state.ID.ValueString()))
		return
	}

	if err := r.client.DeleteRedirect(ctx, id); err != nil && !errors.Is(err, client.ErrNotFound) {
		resp.Diagnostics.AddError("Failed to delete redirect", err.Error())
	}
}

func (r *RedirectResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	if _, err := strconv.ParseInt(req.ID, 10, 64); err != nil {
		resp.Diagnostics.AddError("Invalid ID", fmt.Sprintf("Cannot parse redirect ID %q as integer", req.ID))
		return
	}
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("id"), req.ID)...)
}

// buildRedirectUpdateRequest builds the update body. A null nullable field
// clears it on the server; nice_id is sent only when it changes.
func buildRedirectUpdateRequest(plan *RedirectModel, currentNiceID string) *client.UpdateRedirectRequest {
	req := &client.UpdateRedirectRequest{
		DomainID:        tfconv.PtrFromKnownString(plan.DomainID),
		Subdomain:       tfconv.PtrFromKnownString(plan.Subdomain),
		MatchPath:       tfconv.PtrFromKnownString(plan.MatchPath),
		RewritePath:     tfconv.PtrFromKnownString(plan.RewritePath),
		RewritePathType: tfconv.PtrFromKnownString(plan.RewritePathType),
		Name:            tfconv.PtrFromKnownString(plan.Name),
		DestinationHost: tfconv.PtrFromKnownString(plan.DestinationHost),
		PathMatchType:   tfconv.PtrFromKnownString(plan.PathMatchType),
	}
	req.ResourceID = tfconv.PtrFromKnownInt64AsInt(plan.ResourceID)
	if !plan.NiceID.IsNull() && !plan.NiceID.IsUnknown() && plan.NiceID.ValueString() != currentNiceID {
		v := plan.NiceID.ValueString()
		req.NiceID = &v
	}
	req.Priority = tfconv.PtrFromKnownInt64AsInt(plan.Priority)
	req.Permanent = tfconv.PtrFromKnownBool(plan.Permanent)
	req.SSL = tfconv.PtrFromKnownBool(plan.SSL)
	req.Enabled = tfconv.PtrFromKnownBool(plan.Enabled)
	return req
}

// hydrateRedirectState copies a server redirect into the model. A null
// priority keeps the known value, else the default.
func hydrateRedirectState(m *RedirectModel, r *client.Redirect) {
	m.ID = types.StringValue(strconv.Itoa(r.RedirectID))
	m.NiceID = types.StringValue(r.NiceID)
	m.Name = types.StringValue(r.Name)
	m.DestinationHost = types.StringValue(r.DestinationHost)
	m.ResourceID = tfconv.Int64FromIntPtr(r.ResourceID)
	m.DomainID = tfconv.StringFromPtr(r.DomainID)
	m.Subdomain = tfconv.StringFromPtr(r.Subdomain)
	m.PathMatchType = types.StringValue(r.PathMatchType)
	m.MatchPath = tfconv.StringFromPtr(r.MatchPath)
	m.RewritePath = tfconv.StringFromPtr(r.RewritePath)
	m.RewritePathType = tfconv.StringFromPtr(r.RewritePathType)
	switch {
	case r.Priority != nil:
		m.Priority = types.Int64Value(int64(*r.Priority))
	case m.Priority.IsNull() || m.Priority.IsUnknown():
		m.Priority = types.Int64Value(int64(r.PriorityOr(defaultRedirectPriority)))
	}
	m.Permanent = types.BoolValue(r.Permanent)
	m.SSL = types.BoolValue(r.SSL)
	m.Enabled = types.BoolValue(r.Enabled)
	m.ResourceFullDomain = tfconv.StringFromPtr(r.ResourceFullDomain)
	m.BaseDomain = tfconv.StringFromPtr(r.BaseDomain)
}

// keepEquivalentValues keeps prior values in got when the server only
// normalized them (null vs "", host case), avoiding spurious diffs. Real
// differences come from the server.
func keepEquivalentValues(prior, got *RedirectModel) {
	keepNull := func(p types.String, g *types.String) {
		if p.IsNull() && !g.IsNull() && !g.IsUnknown() && g.ValueString() == "" {
			*g = p
		}
	}
	keepHost := func(p types.String, g *types.String) {
		if p.IsNull() || p.IsUnknown() || g.IsNull() || g.IsUnknown() {
			return
		}
		if strings.EqualFold(strings.TrimSpace(p.ValueString()), strings.TrimSpace(g.ValueString())) {
			*g = p
		}
	}
	keepNull(prior.Subdomain, &got.Subdomain)
	keepNull(prior.MatchPath, &got.MatchPath)
	keepNull(prior.RewritePath, &got.RewritePath)
	keepNull(prior.RewritePathType, &got.RewritePathType)
	keepNull(prior.DomainID, &got.DomainID)
	keepHost(prior.DestinationHost, &got.DestinationHost)
	keepHost(prior.Subdomain, &got.Subdomain)
	if !prior.Name.IsNull() && !prior.Name.IsUnknown() && !got.Name.IsNull() &&
		strings.TrimSpace(prior.Name.ValueString()) == strings.TrimSpace(got.Name.ValueString()) {
		got.Name = prior.Name
	}
}

// keepWhenAttachmentUnchanged keeps the state value of a joined field while
// resource_id and domain_id are unchanged.
type keepWhenAttachmentUnchanged struct{}

func (keepWhenAttachmentUnchanged) Description(context.Context) string {
	return "Keeps the prior value while resource_id and domain_id are unchanged."
}

func (m keepWhenAttachmentUnchanged) MarkdownDescription(ctx context.Context) string {
	return m.Description(ctx)
}

func (keepWhenAttachmentUnchanged) PlanModifyString(ctx context.Context, req planmodifier.StringRequest, resp *planmodifier.StringResponse) {
	if req.State.Raw.IsNull() {
		return
	}
	if req.StateValue.IsNull() || req.StateValue.IsUnknown() {
		return
	}
	if !req.PlanValue.IsUnknown() {
		return
	}
	var planRes, stateRes types.Int64
	var planDom, stateDom types.String
	for _, g := range []struct {
		src interface {
			GetAttribute(context.Context, path.Path, any) diag.Diagnostics
		}
		p   path.Path
		dst any
	}{
		{req.Plan, path.Root("resource_id"), &planRes},
		{req.Plan, path.Root("domain_id"), &planDom},
		{req.State, path.Root("resource_id"), &stateRes},
		{req.State, path.Root("domain_id"), &stateDom},
	} {
		if d := g.src.GetAttribute(ctx, g.p, g.dst); d.HasError() {
			return
		}
	}
	if planRes.IsUnknown() || planDom.IsUnknown() {
		return
	}
	if planRes.Equal(stateRes) && planDom.Equal(stateDom) {
		resp.PlanValue = req.StateValue
	}
}
